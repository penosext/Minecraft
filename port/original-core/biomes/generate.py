#!/usr/bin/env python3
"""Generate include-only adapted, namespace-isolated original layer sources.

Never writes upstream. --check validates source pins, generated bytes, manifest,
and every preserved source byte range (including every cpp function body).
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
UPSTREAM = ROOT.parent.parent / 'upstream' / 'Minecraft.World'
LAYERS = '''Layer AddIslandLayer AddMushroomIslandLayer AddSnowLayer BiomeInitLayer
BiomeOverrideLayer DownfallLayer DownfallMixerLayer FlatLayer FuzzyZoomLayer
GrowMushroomIslandLayer IslandLayer RegionHillsLayer RiverInitLayer RiverLayer
RiverMixerLayer ShoreLayer SmoothLayer SmoothZoomLayer SwampRiversLayer
TemperatureLayer TemperatureMixerLayer VoronoiZoom ZoomLayer'''.split()
SOURCES = LAYERS + ['IntCache', 'LevelType']
HEADERS = ['Layer'] + [n for n in LAYERS if n != 'Layer'] + ['IntCache', 'LevelType']
INCLUDE = re.compile(rb'^[ \t]*(?:\xef\xbb\xbf)?#[ \t]*include[^\r\n]*(?:\r?\n|$)', re.M)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def span(text, marker):
    start = text.index(marker)
    brace = text.index('{', start)
    depth, pos = 1, brace + 1
    while depth:
        if text[pos] == '{':
            depth += 1
        elif text[pos] == '}':
            depth -= 1
        pos += 1
    return start, pos


def source(name):
    return (UPSTREAM / name).read_bytes()


def adapt(name):
    data = source(name)
    out = bytearray(b'#include "PlatformPch.h"\nnamespace original_layers {\n')
    ranges, removed, offset = [], [], 0
    for m in INCLUDE.finditer(data):
        if m.start() > offset:
            kept = data[offset:m.start()]
            ranges.append({'source_start': offset, 'source_end': m.start(),
                           'generated_start': len(out), 'sha256': sha(kept)})
            out.extend(kept)
        removed.append({'start': m.start(), 'end': m.end(),
                        'bytes': m.group().decode('utf-8-sig').rstrip()})
        offset = m.end()
    if offset < len(data):
        kept = data[offset:]
        ranges.append({'source_start': offset, 'source_end': len(data),
                       'generated_start': len(out), 'sha256': sha(kept)})
        out.extend(kept)
    out.extend(b'\n} // namespace original_layers\n')
    # Function signatures/bodies get an additional per-function range/hash.
    # The stronger preserved_ranges audit also covers comments, preprocessor
    # branches and every byte outside include lines, not just active functions.
    functions = []
    signature = re.compile(rb'^[^\r\n;{}#]*\b(?:\w+::)+(?:~?\w+)\([^\r\n;{}]*\)[^\r\n;{}]*\r?\n\{', re.M)
    for m in signature.finditer(data):
        a = m.start()
        brace = data.index(b'{', m.start(), m.end())
        depth, pos = 1, brace + 1
        while depth:
            if data[pos:pos + 1] == b'{':
                depth += 1
            elif data[pos:pos + 1] == b'}':
                depth -= 1
            pos += 1
        functions.append({'signature': data[a:brace].decode().strip(),
                          'source_start': a, 'source_end': pos,
                          'line': data[:a].count(b'\n') + 1,
                          'sha256': sha(data[a:pos]),
                          'function_body_sha256': sha(data[brace:pos])})
    if not functions:
        raise RuntimeError('No original functions inventoried in ' + name)
    return bytes(out), {'source': name, 'source_sha256': sha(data),
                        'generated_sha256': sha(out), 'preserved_ranges': ranges,
                        'functions': functions,
                        'removed_include_lines_only': removed}


def evidence(name, text, start, end):
    data = source(name)
    a = len(text[:start].encode('utf-8'))
    b = len(text[:end].encode('utf-8'))
    return {'source': name, 'start': a, 'end': b,
            'line': text[:start].count('\n') + 1,
            'sha256': sha(data[a:b]), 'text': text[start:end]}


def strip_comments(text):
    return re.sub(r'//[^\n]*|/\*.*?\*/', '', text, flags=re.S)


def biome_table():
    text = source('Biome.cpp').decode('utf-8')
    a, b = span(text, 'Biome::Biome(int id)')
    ctor = strip_comments(text[a:b])
    defaults = {}
    for field in ['depth', 'scale', 'temperature', 'downfall']:
        defaults[field] = re.search(r'\b' + field + r'\s*=\s*([^;]+);', ctor).group(1)
    tile = source('Tile.h').decode('utf-8')
    tiles = {}
    for name in ['grass_Id', 'dirt_Id', 'sand_Id', 'mycel_Id']:
        tiles[name] = int(re.search(r'\b' + name + r'\s*=\s*(\d+)', tile).group(1))
    for field in ['topMaterial', 'material']:
        name = re.search(r'\b' + field + r'\s*=\s*static_cast<\w+>\(Tile::(\w+)\)', ctor).group(1)
        defaults[field] = tiles[name]
    records = []
    for m in re.finditer(r'^\s*Biome::(\w+)\s*=\s*\(new (\w+)\((\d+)\)\)([^;]*);', text, re.M):
        name, cls, id_, chain = m.groups()
        fields = defaults.copy()
        fn = cls + ('.h' if cls in ['OceanBiome', 'RiverBiome'] else '.cpp')
        subclass = source(fn).decode('utf-8')
        ca, cb = span(subclass, cls + '(' if fn.endswith('.h') else cls + '::' + cls + '(')
        body = strip_comments(subclass[ca:cb])
        for field in ['topMaterial', 'material']:
            change = re.search(r'\b' + field + r'\s*=\s*static_cast<\w+>\(Tile::(\w+)\)', body)
            if change:
                fields[field] = tiles[change.group(1)]
        if re.search(r'\b(?:depth|scale|temperature|downfall)\s*=', body):
            raise RuntimeError('Unexpected subclass terrain field assignment: ' + cls)
        for method, names in [('setDepthAndScale', ['depth', 'scale']),
                              ('setTemperatureAndDownfall', ['temperature', 'downfall'])]:
            call = re.search(method + r'\(([^,]+),\s*([^)]+)\)', chain)
            if call:
                for field, value in zip(names, call.groups()):
                    fields[field] = value.strip()
        records.append({'name': name, 'class': cls, 'id': int(id_), 'fields': fields,
                        'registration': evidence('Biome.cpp', text, m.start(), m.end()),
                        'base_constructor': evidence('Biome.cpp', text, a, b),
                        'subclass_constructor': evidence(fn, subclass, ca, cb)})
    if [r['id'] for r in records] != list(range(23)):
        raise RuntimeError('Expected the original 23 registered biome IDs')
    return records, tiles


def float_literal(value):
    return value if value.endswith('f') else value + '.0f' if '.' not in value else value + 'f'


def generate():
    outputs, entries = {}, []
    for name in [n + '.cpp' for n in SOURCES]:
        outputs[name], entry = adapt(name)
        entries.append(entry)
    # Put all original declarations in one guarded namespace-isolated header;
    # include order starts with the original array wrapper and base Layer.
    arr = source('ArrayWithLength.h')
    template_end = arr.index(b'// TODO 4J Stu')
    original_array = arr[arr.index(b'template <class T>'):template_end]
    # No item/entity declarations enter this library. The original shallow
    # arrayWithLength template (including its full methods) is copied bytewise.
    header = b'#pragma once\nnamespace original_layers {\n' + original_array
    header += b'\nclass Biome; class Layer;\n'
    header += b'typedef arrayWithLength<int> intArray;\ntypedef arrayWithLength<byte> byteArray;\n'
    header += b'typedef arrayWithLength<Biome*> BiomeArray;\n'
    header += b'typedef arrayWithLength<shared_ptr<Layer>> LayerArray;\n'
    for name in HEADERS:
        raw = source(name + '.h')
        header += b'\n' + INCLUDE.sub(b'', raw)
    header += b'\n} // namespace original_layers\n#include "BiomeAdapter.h"\n'
    outputs['OriginalHeaders.h'] = header
    entries.append({'source': 'ArrayWithLength.h', 'source_sha256': sha(arr),
                    'extracted_template_sha256': sha(original_array),
                    'start': arr.index(b'template <class T>'), 'end': template_end})
    records, tiles = biome_table()
    decl = '''#pragma once
namespace original_layers {
// Data-only adapter. No decorator, mob lists, tiles, or game objects are built.
struct Biome {
    int id;
    float depth, scale, temperature, downfall;
    byte topMaterial, material;
    int getTemperatureInt();
    int getDownfallInt();
    static Biome* biomes[256];
'''
    for record in records:
        decl += '    static Biome* ' + record['name'] + ';\n'
    decl += '};\n}\n'
    outputs['BiomeAdapter.h'] = decl.encode()
    table = '#include "PlatformPch.h"\nnamespace original_layers {\nnamespace {\nBiome storage[] = {\n'
    for r in records:
        f = r['fields']
        values = [str(r['id'])] + [float_literal(f[k]) for k in ['depth', 'scale', 'temperature', 'downfall']]
        values += [str(f['topMaterial']), str(f['material'])]
        table += '    {' + ', '.join(values) + '}, // ' + r['name'] + '\n'
    table += '};\n}\nBiome* Biome::biomes[256] = {'
    table += ', '.join('&storage[' + str(r['id']) + ']' for r in records) + '};\n'
    for r in records:
        table += 'Biome* Biome::' + r['name'] + ' = &storage[' + str(r['id']) + '];\n'
    methods = []
    for method in ['int Biome::getTemperatureInt()', 'int Biome::getDownfallInt()']:
        a, b = span(text := source('Biome.cpp').decode(), method)
        table += text[a:b] + '\n'
        methods.append(evidence('Biome.cpp', text, a, b))
    table += '} // namespace original_layers\n'
    outputs['BiomeAdapter.cpp'] = table.encode()
    # nextLong is not a dependency of layers. Keep forensic source evidence;
    # do not quietly replace or compile a corrected Random implementation.
    random = source('Random.cpp').decode()
    ra, rb = span(random, 'int64_t Random::nextLong()')
    manifest = {'format': 1, 'namespace': 'original_layers',
                'cpp_rule': 'remove include directive lines only; prefix PCH and wrap namespace; every other byte unchanged',
                'pinned_inputs_sha256': json.loads((ROOT / 'upstream-sha256.json').read_text()),
                'dependency_adapters': {
                    'LevelType': 'All original cpp functions and class declaration retained; original staticCtor called once by Source',
                    'Biome': '23 data-only registrations projected from original base/subclass constructors and setter chain; no decorators/entities',
                    'SharedConstants': 'No symbol references in the original Layer pipeline; not linked or stubbed',
                    'IntCache': 'All original cpp functions/class retained; native thread_local TLS primitives and Reset before/after every query',
                    'System': 'Only required arraycopy primitive mapped to checked native memmove'},
                'sources': entries, 'biomes': records, 'tile_ids': tiles,
                'extracted_original_methods': methods,
                'known_ub': [
                    {'kind': 'Random::nextLong signed negative left shift',
                     'compiled_by_biome_library': False,
                     'action': 'Unmodified upstream; not used by original Layer RNG',
                     'evidence': evidence('Random.cpp', random, ra, rb)},
                    {'kind': 'Layer/FuzzyZoom/Zoom/SmoothZoom/Voronoi signed negative coordinate left shifts',
                     'action': 'Original bytes retained; -fwrapv does not define negative signed left shift. Native compiler behavior tested, not claimed portable ISO semantics.'}],
                'options': {'cpp_standard': 17, 'flags': ['-fwrapv', '-ffp-contract=off', '-fno-fast-math'],
                            'optional_game_debug_override': False,
                            'native_optional_BiomeOverrideLayer': 'real stdio file adapter, not selected by production pipeline'},
                'generated_sha256': {n: sha(d) for n, d in outputs.items()},
                'validation_limits': 'Tests compare adapter against original compiled layer pipeline and consistency properties, not a running original console or chunk oracle.'}
    outputs['source-manifest.json'] = (json.dumps(manifest, indent=2, ensure_ascii=False) + '\n').encode()
    return outputs


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    pins = json.loads((ROOT / 'upstream-sha256.json').read_text())
    for name, expected in pins.items():
        if sha(source(name)) != expected:
            raise SystemExit('Upstream source pin mismatch: ' + name)
    outputs = generate()
    args.output.mkdir(parents=True, exist_ok=True)
    for name, data in outputs.items():
        path = args.output / name
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit('Generated byte audit failed: ' + str(path))
        else:
            if not path.is_file() or path.read_bytes() != data:
                path.write_bytes(data)
    # Explicitly check each source segment against the generated output.
    manifest = json.loads(outputs['source-manifest.json'])
    for entry in manifest['sources']:
        if 'preserved_ranges' not in entry:
            continue
        src, dst = source(entry['source']), outputs[entry['source']]
        for r in entry['preserved_ranges']:
            a, b, c = r['source_start'], r['source_end'], r['generated_start']
            if src[a:b] != dst[c:c + b - a]:
                raise SystemExit('Preserved source range mismatch: ' + entry['source'])
    print('original_biomes source-byte audit OK: 26 original cpp units, 23 biome registrations')


if __name__ == '__main__':
    main()
