#!/usr/bin/env python3
"""Offline, exact terrain crops. --check never writes (including shared builds)."""
import argparse
import hashlib
import json
from pathlib import Path
import re

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ATLAS_SHA256 = 'f870d386df7e6765eba320f15816c76a8673603d0e46b535fc9e6e6eac12805f'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def generate():
    atlas_path = ROOT / 'port/assets/terrain.png'
    mapping_path = ROOT / 'port/upstream/Minecraft.Client/PreStitchedTextureMap.cpp'
    catalog_path = ROOT / 'jsapi/build/generated/LegacyCatalog.hpp'
    data = atlas_path.read_bytes()
    if sha(data) != ATLAS_SHA256:
        raise ValueError('terrain.png differs from pinned source; refusing guessed textures')
    image = Image.open(atlas_path).convert('RGBA')
    if image.size != (256, 512):
        raise ValueError('Expected original 16-column, 32-row atlas')
    source = mapping_path.read_text()
    # Restrict to terrain branch, not items' identically named ADD_ICON entries.
    terrain = source[source.index('float vertRatio = 1.0f/32.0f;'):]
    mappings = {}
    terrain = re.sub(r'//[^\n]*', '', terrain)
    for row, col, name in re.findall(r'ADD_ICON\(\s*(\d+)\s*,\s*(\d+)\s*,\s*L"([^"]+)"\s*\)', terrain):
        rect = [int(col) * 16, int(row) * 16, 16, 16]
        if name in mappings and mappings[name] != rect:
            raise ValueError(f'Ambiguous source mapping: {name}')
        mappings[name] = rect
    # Existing generated catalog supplies face NAMES only, never atlas positions
    # (its atlas is repacked). Unknown source names have NO stone fallback.
    faces = set(re.findall(r'L"([^"]+)"', catalog_path.read_text().split('kBlockSpecs[] = {')[1]))
    names = [f'destroy_{stage}' for stage in range(10)] + sorted(faces & mappings.keys())
    missing = sorted(faces - mappings.keys())
    records, pixels = [], []
    for name in names:
        x, y, w, h = mappings[name]
        if x < 0 or y < 0 or x + w > image.width or y + h > image.height:
            raise ValueError(f'Outside source atlas: {name}')
        tile = image.crop((x, y, x + w, y + h))
        records.append({'name': name, 'rect': [x, y, w, h], 'rgba_sha256': sha(tile.tobytes())})
        pixels.append([a << 24 | r << 16 | g << 8 | b for r, g, b, a in tile.getdata()])
    lines = ['// Generated by tools/generate-break-textures.py; exact RGBA crops, no resampling.',
             '#pragma once', '#include <cstdint>', 'namespace mcfx::textures {',
             f'inline constexpr const char* TerrainSha256 = "{ATLAS_SHA256}";',
             'inline constexpr const wchar_t* Names[] = {']
    lines += [f'    L"{name}",' for name in names]
    lines += ['};', 'inline constexpr uint32_t Pixels[][256] = {']
    for name, tile in zip(names, pixels):
        lines.append(f'    {{ // {name}')
        for i in range(0, 256, 8):
            lines.append('        ' + ', '.join(f'0x{v:08x}u' for v in tile[i:i+8]) + ',')
        lines.append('    },')
    lines += ['};', '} // namespace mcfx::textures', '']
    manifest = {
        'atlas': 'port/assets/terrain.png', 'atlas_sha256': sha(data),
        'mapping_source': str(mapping_path.relative_to(ROOT)),
        'mapping_sha256': sha(mapping_path.read_bytes()),
        'catalog_names_source': str(catalog_path.relative_to(ROOT)),
        'catalog_sha256': sha(catalog_path.read_bytes()),
        'stage_alias': 'destroy_stage0..9 = upstream destroy_0..9 (LevelRenderer.cpp registerTextures)',
        'pixel_format': 'RGBA SHA-256 before exact ARGB32 packing, nearest sampling',
        'crack_blend': 'alpha <= 0.1 discarded; surviving texels use source GL_DST_COLOR/GL_SRC_COLOR (2*src*dst)',
        'particle_source': 'ParticleEngine.cpp destroy: 4x4x4; TerrainParticle.cpp: face 0 texture, quarter-tile fragments',
        'limitations': ['Cracks only on full-height cube/grass shapes; anvil/dragon egg excluded.',
                         'Occlusion uses conservative voxel DDA, matching World::pick, not special-shape triangles.',
                         'Particle gravity/lifetime are bounded seconds-based approximation; no collision or biome tint.',
                         'Missing source face mappings are skipped without substituted textures.'],
        'missing_face_textures': missing, 'textures': records,
    }
    return {
        ROOT / 'jsapi/src/MinecraftRenderer/generatedBreakTextures.hpp': '\n'.join(lines),
        ROOT / 'port/assets/break-textures.source.json': json.dumps(manifest, indent=2) + '\n',
    }, missing


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs, missing = generate()
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale or missing output: {path}')
        else:
            path.write_text(content)
    print('Exact break textures verified; missing face mappings: ' + (', '.join(missing) or 'none'))


if __name__ == '__main__':
    main()
