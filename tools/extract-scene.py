#!/usr/bin/env python3
"""Extract byte-identical original day/sky math and biome spawn weights.

The class shells and clear-weather boundary live in Scene.cpp, not upstream.
--check checks both output and provenance without modifying either file.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("renderer_extractor", ROOT / "tools/extract-renderer.py")
helper = importlib.util.module_from_spec(spec)
spec.loader.exec_module(helper)
WORLD = "port/upstream/Minecraft.World/"
TARGETS = (
    ("Dimension.cpp", "float Dimension::getTimeOfDay(int64_t time, float a) const"),
    ("Mth.cpp", "void Mth::init()"),
    ("Mth.cpp", "float Mth::sin(float i)"),
    ("Mth.cpp", "float Mth::cos(float i)"),
    ("Level.cpp", "float Level::getSkyDarken(float a)"),
    ("Level.cpp", "int Level::getOldSkyDarken(float a)"),
    ("Level.cpp", "float Level::getSunAngle(float a)"),
)
INCLUDE = "LegacyScene.inc"
MANIFEST = "LegacyScene.manifest.json"


def generate(root):
    output = bytearray(b"// Generated by tools/extract-scene.py. Do not edit.\n"
                       b"// Function and constant bytes are copied verbatim from upstream.\n"
                       b"namespace mcscene_original {\n")
    sources, functions, constants, rules = {}, [], [], []

    def source(name):
        path = WORLD + name
        if path not in sources:
            raw = (root / path).read_bytes()
            sources[path] = (raw, helper.mask_cpp(raw))
        return path, *sources[path]

    def append(name, start, end, kind, **fields):
        path, raw, _ = source(name)
        body = raw[start:end]
        entry = dict(source_file=path, start_byte=start, end_byte=end,
                     start_line=raw.count(b"\n", 0, start) + 1,
                     end_line=raw.count(b"\n", 0, end - 1) + 1,
                     sha256=hashlib.sha256(body).hexdigest(), **fields)
        output.extend((f"// source: {path}:{entry['start_line']}-{entry['end_line']}\n").encode())
        entry["generated_start_byte"] = len(output)
        output.extend(body)
        entry["generated_end_byte"] = len(output)
        output.extend(b"\n")
        kind.append(entry)

    for name, signature in TARGETS:
        _, raw, masked = source(name)
        _, entry = helper.extract_function(raw, masked, signature)
        append(name, entry["start_byte"], entry["end_byte"], functions, signature=signature)

    # Original constants, including the float (not double) PI and exact table
    # scale; no replacement trigonometric approximation is introduced.
    for name, expression in (
        ("Mth.cpp", rb"^float \*Mth::_sin = nullptr;"),
        ("Mth.cpp", rb"^const float Mth::sinScale = .*;"),
    ):
        _, raw, _ = source(name)
        match = re.search(expression, raw, re.MULTILINE)
        if not match:
            raise ValueError(f"missing constant in {name}")
        append(name, match.start(), match.end(), constants)

    # Verify the class-shell constants against original definitions too.
    for name, expression in (
        ("Definitions.h", rb"^#define PI \(3\.141592654f\)"),
        ("Level.h", rb"^[ \t]*static const int TICKS_PER_DAY = 20 \* 60 \* 20;[^\r\n]*"),
    ):
        path, raw, _ = source(name)
        match = re.search(expression, raw, re.MULTILINE)
        if not match:
            raise ValueError(f"original shell constant changed in {name}")
        constants.append(dict(source_file=path, start_byte=match.start(), end_byte=match.end(),
                              sha256=hashlib.sha256(match.group()).hexdigest(),
                              source_text=match.group().decode()))

    output.extend(b"\nstruct SpawnWeight { MobKind kind; int weight, minimum, maximum; };\n"
                  b"constexpr SpawnWeight passiveWeights[] = {\n")
    for symbol, kind in (("PIG", "Pig"), ("COW", "Cow"), ("SHEEP", "Sheep"), ("CHICKEN", "Chicken")):
        path, raw, _ = source("Biome.cpp")
        pattern = (rb"^[ \t]*friendlies(?:_chicken)?\.push_back\(new MobSpawnerData\(eTYPE_" +
                   symbol.encode() + rb", (\d+), (\d+), (\d+)\)\);[^\r\n]*")
        match = re.search(pattern, raw, re.MULTILINE)
        if not match:
            raise ValueError(f"missing original {symbol} spawn weight")
        values = [int(value) for value in match.groups()]
        output.extend(f"    {{MobKind::{kind}, {values[0]}, {values[1]}, {values[2]}}},\n".encode())
        rules.append(dict(source_file=path, source_line=raw.count(b"\n", 0, match.start()) + 1,
                          sha256=hashlib.sha256(match.group()).hexdigest(),
                          source_text=match.group().decode(), kind=kind, weight=values[0],
                          minimum=values[1], maximum=values[2], adaptation="parsed original constructor fields"))
    output.extend(b"};\n} // namespace mcscene_original\n")
    # These are provenance references, NOT claims that the full spawn algorithms
    # (light engine, entity factories, categories, chunk search) have been ported.
    for name, signature in (("Animal.cpp", "bool Animal::canSpawn()"),
                            ("Monster.cpp", "bool Monster::isDarkEnoughToSpawn()"),
                            ("Monster.cpp", "bool Monster::canSpawn()"),
                            ("MobSpawner.cpp", "bool MobSpawner::isSpawnPositionOk(MobCategory *category, Level *level, int x, int y, int z)")):
        path, raw, masked = source(name)
        body, entry = helper.extract_function(raw, masked, signature)
        entry.update(source_file=path, source_text=body.decode(), adaptation="reference only; platform spawn approximation")
        rules.append(entry)
    manifest = dict(schema_version=1, generator="tools/extract-scene.py", generated_file=INCLUDE,
                    generated_sha256=hashlib.sha256(output).hexdigest(), byte_range_end="exclusive",
                    functions=functions, constants=constants, spawn_rules=rules,
                    boundaries=["clear weather only; rain and thunder are zero",
                                "default biome passive weights; no biome-specific population model",
                                "near-player bounded population is platform behavior, not upstream chunk spawner",
                                "passive dry grass and raw daytime light >8; zombies night/darkness only",
                                "lightweight wander, AABB collision and gravity; NOT original Mob/Goal/pathfinding"],
                    sources=[dict(source_file=path, sha256=hashlib.sha256(raw).hexdigest())
                             for path, (raw, _) in sources.items()])
    return {INCLUDE: bytes(output), MANIFEST: (json.dumps(manifest, indent=2) + "\n").encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    directory = args.output_dir or args.root / "jsapi/build/generated"
    try:
        for name, content in generate(args.root).items():
            path = directory / name
            if args.check:
                if not path.is_file() or path.read_bytes() != content:
                    raise ValueError(f"missing or stale generated file: {path}")
            else:
                directory.mkdir(parents=True, exist_ok=True)
                if not path.is_file() or path.read_bytes() != content:
                    path.write_bytes(content)
    except (ValueError, OSError) as error:
        print(f"extract-scene: {error}", file=sys.stderr)
        return 1
    print(f"{'Verified' if args.check else 'Extracted'} {len(TARGETS)} original scene functions in {directory / INCLUDE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
