#!/usr/bin/env python3
"""Verify original mob PNGs and embed straight ARGB32 (no runtime image loader).

Default output: jsapi/build/generated/MobSkins.hpp. No network; requires Pillow.
--verify-only also checks byte hashes, decoded hashes and recorded provenance.
"""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
# Pinned independently of the editable manifest: (original PNG SHA-256, RGBA SHA-256).
HASHES = {
    'pig': ('0ad7e2885302a58e28512451af7fb433ce17ee9ad47a051b326ef88520cc69c9', 'de6b020f5c85230b75e4e47e5dab38f452006f564c07df4c8da160afce7e2c4e'),
    'cow': ('5b901e770c7d567ac2e46382d2ec3e83bfcbcaaae024f7610b50299ae836773e', '22ef3219d711efa36aafa5d37f68b120b498672ab4bfd932cf349000c1b6221e'),
    'sheep': ('a4c953073c2975e6d8035ba59af7bff84016ba7edfd5fcc5df24907066d1ed6a', '81a3ae4ba18e0d03d80d33aa0f987214c5d565fe51328118b57d160703c5ecb4'),
    'sheep_fur': ('9f4ef6ad8906027ad6e5ebb9259f4107c449cfbfe703f641d02b0a785417964d', 'e54c26a6826c2fe5a5a5198dd592057d5e1d4d71e5b108a7d09d85e880bb6ba6'),
    'chicken': ('f274296053d7993975270300388cd184635010a7082cf56c537e903274b12216', 'c3fe1f1ee126b934e6b9aff41327898e052bb8d2ede4d36de652e4beaf25eca2'),
    'creeper': ('c27e7c20555f1bf5ef1cd848a4291f90465000708185e6743e72b8adffed2a4b', 'b92f0ff9d25042dbe92d7d7a332d56e11367183ba7142990187f4e046af50d38'),
    'zombie': ('6bd21f2f5f873d5b2d70ea84451ee616a3e888cdfb0d90b1fb59681a65a156a1', 'd1857c20ab8bdd086bf691f0f0b660692111caad74086c8629735689898e1c0c'),
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input-dir', type=Path, default=ROOT / 'port/assets/mobs')
    parser.add_argument('--output', type=Path, default=ROOT / 'jsapi/build/generated/MobSkins.hpp')
    parser.add_argument('--verify-only', action='store_true')
    args = parser.parse_args()
    manifest = json.loads((args.input_dir / 'sources.json').read_text(encoding='utf-8'))
    lines = ['// Generated by tools/generate-mobs.py; do not edit.',
             '// Original Common/res/mob assets, see port/assets/mobs/sources.json.',
             '#pragma once', '#include <cstdint>', 'namespace mobskins {',
             'constexpr int kWidth = 64, kHeight = 32;',
             'struct Skin { const char* name; const uint32_t* pixels; const char* sourceSha256; const char* rgbaSha256; };']
    entries = []
    for name, (source_hash, rgba_hash) in HASHES.items():
        path = args.input_dir / (name + '.png')
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != source_hash:
            raise ValueError(f'{name}: original PNG SHA-256 mismatch')
        with Image.open(path) as image:
            if image.size != (64, 32) or image.mode != 'RGBA':
                raise ValueError(f'{name}: expected original 64x32 RGBA PNG')
            rgba = image.tobytes()
        if hashlib.sha256(rgba).hexdigest() != rgba_hash:
            raise ValueError(f'{name}: decoded RGBA SHA-256 mismatch')
        entry = manifest['assets'][name]
        if (entry['source_sha256'], entry['decoded_rgba_sha256']) != (source_hash, rgba_hash):
            raise ValueError(f'{name}: provenance hash mismatch')
        git_hash = hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest()
        if entry['source_git_blob_sha1'] != git_hash:
            raise ValueError(f'{name}: original git blob hash mismatch')
        symbol = ''.join(word.title() for word in name.split('_'))
        pixels = [(a << 24) | (r << 16) | (g << 8) | b
                  for r, g, b, a in zip(rgba[0::4], rgba[1::4], rgba[2::4], rgba[3::4])]
        lines.append(f'constexpr uint32_t k{symbol}Pixels[kWidth * kHeight] = {{')
        for offset in range(0, len(pixels), 8):
            lines.append('    ' + ', '.join(f'0x{p:08x}u' for p in pixels[offset:offset+8]) + ',')
        lines += ['};', f'constexpr Skin k{symbol}{{"{name}", k{symbol}Pixels, "{source_hash}", "{rgba_hash}"}};']
        entries.append(f'&k{symbol}')
        print(f'Verified {name}: {len(data)} bytes, original PNG and RGBA SHA-256')
    lines += ['constexpr const Skin* kAll[] = {' + ', '.join(entries) + '};',
              '} // namespace mobskins', '']
    if not args.verify_only:
        text = '\n'.join(lines)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        if not args.output.exists() or args.output.read_text(encoding='utf-8') != text:
            args.output.write_text(text, encoding='utf-8')
        print(f'Generated {args.output}')


if __name__ == '__main__':
    main()
