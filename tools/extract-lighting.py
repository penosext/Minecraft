#!/usr/bin/env python3
"""Offline byte-preserving sky extraction and source-checked lighting subset.

All outputs stay in port/assets/sky. Re-run with --source-root pointing at the
local original Minecraft.Client/Common/res; otherwise verifies the bundled PNGs.
This deliberately is NOT a port of the complete original Level light engine.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'port/assets/sky'
UP = ROOT / 'port/upstream'
TEXTURES = {
    'sun': ('terrain/sun.png', (32, 32), '59bb3d5c4c5e2bc5cddb10e2e0f2c3dba979b64574a40c1cdc843c2ae9139e9e'),
    'moon_phases': ('1_2_2/terrain/moon_phases.png', (128, 64), '6317ed4c6ad8c2ed41276ec6057efd78d3acd27cf6d19ffe0d11751d8eaf83f3'),
}

def sha(b):
    return hashlib.sha256(b).hexdigest()


def write(path, data):
    data = data.encode() if isinstance(data, str) else data
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-root', type=Path)
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    manifest = {'textures': {}, 'sources': {}, 'tileLighting': {},
        'sky': {'sourcefn': 'LevelRenderer::renderSky', 'rotation': 'Ry(-90deg)*Rx(timeOfDay*360deg)',
                'sun': {'y': 100, 'halfSize': 30}, 'moon': {'y': -100, 'halfSize': 20, 'atlas': [4, 2]},
                'blend': 'SRC_ALPHA,ONE; original straight RGBA, black stays black',
                'projection': 'GameRenderer::setupCamera/gluPerspective: vertical base FOV 70deg; shared focalLength(height)',
                'phase': 'Scene timeOfDay already applies Dimension::getTimeOfDay; moonPhase supplied separately, default full moon'},
        'limitations': [
            'Bounded resident render window (production 96x256x96), NOT the full original Level/LevelChunk engine.',
            'Window top assumes open sky; lateral/bottom boundaries are closed to incoming light. No outside-window chunk lookup.',
            '15-level vertical skylight columns plus six-neighbour destination-opacity attenuation; full rebuild only on cache miss.',
            'Two independent byte vectors (2*volume bytes). Cache key: path, origin, dimensions, terrain revision and data pointer.',
            'Scalar max(sky daylight ramp, block ramp), not original RGB lightmap, gamma, torch flicker or weather.',
            'AO subset: bilinear four-corner average of face-centre and three neighbours, source 0.2/1 shade; full cubes only.',
            'No directional shadow map: roof/cave darkening follows original diffuse voxel skylight rather than solar ray shadows.',
            'Original textures use nearest sampling here; not the original GL filtering/mipmap pipeline.',
            'Source sky stars, dawn fan, clouds, weather and non-natural dimension skies are not ported here.',
            'Physical shapes and collision metadata are unchanged; stairs/slabs retain source whole-cell lightBlock=255; inset opaque special faces use above/four-side max brightness subset.'
        ]}
    h = ['// Generated by tools/extract-lighting.py; exact source pixels, no analytic disc.',
         '#pragma once', '#include <cstdint>', 'namespace skytextures {']
    for name, (rel, size, expected) in TEXTURES.items():
        dest = OUT / (name + '.png')
        data = (args.source_root / rel).read_bytes() if args.source_root else dest.read_bytes()
        if sha(data) != expected:
            raise ValueError(f'{name}: source PNG SHA-256 mismatch: {sha(data)}')
        write(dest, data)
        with Image.open(dest) as image:
            if image.size != size:
                raise ValueError(f'{name}: wrong dimensions {image.size}')
            mode = image.mode
            rgba = image.convert('RGBA').tobytes()
        manifest['textures'][name] = {'sourcefn': rel, 'sourcePngSha256': sha(data),
            'copiedPngSha256': sha(dest.read_bytes()), 'rgbaSha256': sha(rgba),
            'size': size, 'sourceMode': mode, 'byteIdentical': True}
        tag = 'Sun' if name == 'sun' else 'Moon'
        h += [f'constexpr int k{tag}Width = {size[0]}, k{tag}Height = {size[1]};',
              f'constexpr char k{tag}SourceSha256[] = "{sha(data)}";',
              f'constexpr uint32_t k{tag}Pixels[] = {{']
        pixels = [(a << 24) | (r << 16) | (g << 8) | b for r,g,b,a in zip(rgba[::4],rgba[1::4],rgba[2::4],rgba[3::4])]
        for i in range(0, len(pixels), 8):
            h.append('    ' + ', '.join(f'0x{p:08x}u' for p in pixels[i:i+8]) + ',')
        h += ['};']
    h += ['} // namespace skytextures', '']
    write(OUT / 'SkyTextures.hpp', '\n'.join(h))
    sources = set()
    def source(rel):
        path = UP / rel
        data = path.read_bytes()
        manifest['sources'][rel] = {'sha256': sha(data), 'bytes': len(data)}
        sources.add(rel)
        return data.decode('utf-8-sig')
    tile = source('Minecraft.World/Tile.cpp')
    source('Minecraft.World/Tile.h')
    for rel in ['Minecraft.Client/LevelRenderer.cpp', 'Minecraft.Client/GameRenderer.cpp',
                'Minecraft.Client/TileRenderer.cpp', 'Minecraft.World/Dimension.cpp',
                'Minecraft.World/Level.cpp', 'Minecraft.World/LevelChunk.cpp',
                'Minecraft.World/LightLayer.h', 'Minecraft.World/Material.cpp']:
        source(rel)
    # Hash exact function bytes (including original whitespace/comments), not
    # a normalized or reformatted extraction. The lexical scan only finds the
    # closing brace and does not change the hashed byte slice.
    manifest['sourceFunctions'] = {}
    def function_bytes(rel, signature):
        raw = (UP/rel).read_bytes()
        start = raw.index(signature.encode())
        opening = raw.index(b'{', start)
        tokens = rb'//[^\\n]*|/\\*[\\s\\S]*?\\*/|"(?:\\\\.|[^"\\\\])*"|\'(?:\\\\.|[^\'\\\\])*\'|[{}]'
        depth = 0
        for match in re.finditer(tokens, raw[opening:]):
            token = match.group()
            if token == b'{':
                depth += 1
            elif token == b'}':
                depth -= 1
                if depth == 0:
                    end = opening + match.end()
                    manifest['sourceFunctions'][signature] = {'sourcefn': rel, 'byteOffset': start,
                        'bytes': end-start, 'sha256': sha(raw[start:end])}
                    return
        raise ValueError(f'Unclosed original function {signature}')
    for rel, signatures in {
        'Minecraft.Client/LevelRenderer.cpp': ['void LevelRenderer::renderSky(float alpha)'],
        'Minecraft.Client/GameRenderer.cpp': ['float GameRenderer::getFov(float a, bool applyEffects)',
            'void GameRenderer::setupCamera(float a, int eye)', 'void GameRenderer::renderItemInHand(float a, int eye)'],
        'Minecraft.World/Dimension.cpp': ['float Dimension::getTimeOfDay(int64_t time, float a) const',
            'int Dimension::getMoonPhase(int64_t time) const', 'void Dimension::updateLightRamp()'],
        'Minecraft.World/Level.cpp': ['int Level::getExpectedLight('],
        'Minecraft.World/Tile.cpp': ['Tile *Tile::setLightEmission(float f)', 'float Tile::getShadeBrightness('],
        'Minecraft.Client/TileRenderer.cpp': ['bool TileRenderer::tesselateBlockInWorldWithAmbienceOcclusionTexLighting(']
    }.items():
        for signature in signatures:
            function_bytes(rel, signature)
    # Static source-constructor subset, not shape/alpha inference. These classes
    # pass isSolidRender()==false to Tile, including their verified base classes.
    non_solid = {'LiquidTileDynamic','LiquidTileStatic','LeafTile','GlassTile','StainedGlassBlock',
        'TallGrass','DeadBushTile','Bush','Mushroom','TorchTile','FireTile','MobSpawnerTile',
        'ChestTile','RedStoneDustTile','CropTile','DoorTile','LadderTile','RailTile','LeverTile',
        'PressurePlateTile','StoneButtonTile','TopSnowTile','IceTile','CactusTile','ReedTile',
        'FenceTile','ThinFenceTile','VineTile','WaterlilyTile','NetherWartTile','CauldronTile',
        'TheEndPortalFrameTile','CocoaTile','TripWireSourceTile','TripWireTile','FlowerPotTile',
        'CarrotTile','PotatoTile','RepeaterTile','PistonBaseTile','StairTile','FarmTile'}
    entries = {0: (0, 0, False)}
    catalog = (ROOT / 'jsapi/build/generated/LegacyCatalog.hpp').read_text()
    ids = sorted({int(i) for i in re.findall(r', (\d+)\},', catalog)})
    files = {p.stem.lower(): p for p in (UP/'Minecraft.World').glob('*.cpp')}
    for i in ids:
        if i == 0:
            continue
        lines = [l for l in tile.splitlines() if re.search(r'new \w+\('+str(i)+r'[,)]', l)]
        if i in (43, 44):
            lines = [l for l in tile.splitlines() if 'new StoneSlabTile(Tile::' + ('stoneSlab_Id' if i == 43 else 'stoneSlabHalf_Id') in l]
        if len(lines) != 1:
            raise ValueError(f'Unresolved source tile {i}: {lines}')
        line = lines[0]
        cls = re.search(r'new (\w+)\(', line)[1]
        path = files[cls.lower()]
        text = source(str(path.relative_to(UP)))
        opacity = 0 if cls in non_solid or i == 44 else 255
        # Whole-cell override lives in these constructors (not random methods).
        if cls in {'StairTile', 'FarmTile', 'StoneSlabTile', 'WoodSlabTile'}:
            opacity = 255
        override = re.search(r'setLightBlock\((\d+)\)', line)
        if override:
            opacity = int(override[1])
        emission = 0
        m = re.search(r'setLightEmission\(([^)]+)\)', line)
        if m:
            value = m[1].replace('f', '')
            if not re.fullmatch(r'[0-9. /]+', value):
                raise ValueError(value)
            emission = int(15 * eval(value, {'__builtins__': {}}, {}))
        # Exact lightBlock for every currently embedded tile. AO intentionally
        # conservative full-solid-render cube subset (documented above).
        # Glowstone's glass material is neverBuildable, so source
        # Material::isSolidBlocking()==false despite lightBlock==255.
        ao = opacity == 255 and cls not in non_solid and i not in {44, 89}
        entries[i] = (opacity, emission, ao)
        manifest['tileLighting'][str(i)] = {'class': cls, 'sourcefn': line.strip(),
            'lightBlock': opacity, 'emission': emission, 'occludesAO_subset': ao}
    for name in ['HalfSlabTile','StairTile','FarmTile','HalfTransparentTile','TransparentTile','LiquidTile','Bush',
                 'BaseRailTile','BasePressurePlateTile','DiodeTile','ButtonTile','RotatedPillarTile','BaseEntityTile']:
        source(str(files[name.lower()].relative_to(UP)))
    for i, expected in {8: (3,0), 9: (3,0), 10: (255,15), 11: (255,15),
                        18: (1,0), 20: (0,0), 50: (0,14), 79: (3,0), 89: (255,15), 44: (255,0)}.items():
        if entries[i][:2] != expected:
            raise ValueError(f'Original light table contract changed for tile {i}: {entries[i]}')
    table = ['// Generated from original Tile constructor/overrides; see lighting.source.json.',
             '#pragma once', '#include <cstdint>', 'namespace sourcelighting {',
             'struct Tile { uint8_t opacity, emission; bool ao; };', 'constexpr Tile kTiles[256] = {']
    for i in range(256):
        o,e,a = entries.get(i, (0,0,False))
        table.append(f'    {{{o}, {e}, {str(a).lower()}}}, // source tile {i}')
    table += ['};', '} // namespace sourcelighting', '']
    write(OUT/'LightingTables.hpp', '\n'.join(table))
    write(OUT/'lighting.source.json', json.dumps(manifest, indent=2, ensure_ascii=False) + '\n')
    print(f'Verified sun/moon PNG bytes and RGBA; extracted {len(ids)} catalog tile ids into {OUT}')

if __name__ == '__main__':
    main()
