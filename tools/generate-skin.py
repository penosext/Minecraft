#!/usr/bin/env python3
"""Embed the byte-verified original 64x32 Steve skin as straight ARGB32.

Default output: jsapi/build/generated/SteveSkin.hpp. Only that file is written.
Requires Pillow, like generate-terrain.py; no network or runtime image loader.
"""
import argparse
import hashlib
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE_SHA256 = '1a683a41813ff8b6f4633053b38412a506f2e6e666b0351941d0bb48f49534f0'
RGBA_SHA256 = '5de568439f0433e51ed0757ab816d27d7a5a4dcfa746425fe8883c23f3276900'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=ROOT / 'port/assets/steve.png')
    parser.add_argument('--output', type=Path,
                        default=ROOT / 'jsapi/build/generated/SteveSkin.hpp')
    args = parser.parse_args()
    digest = hashlib.sha256(args.input.read_bytes()).hexdigest()
    if digest != SOURCE_SHA256:
        raise ValueError(f'Steve source SHA-256 mismatch: {digest}')
    with Image.open(args.input) as image:
        if image.size != (64, 32) or image.mode != 'RGBA':
            raise ValueError(f'Expected 64x32 RGBA, got {image.size} {image.mode}')
        rgba = image.tobytes()
    rgba_digest = hashlib.sha256(rgba).hexdigest()
    if rgba_digest != RGBA_SHA256:
        raise ValueError(f'Steve decoded RGBA SHA-256 mismatch: {rgba_digest}')
    pixels = [(a << 24) | (r << 16) | (g << 8) | b
              for r, g, b, a in zip(rgba[0::4], rgba[1::4], rgba[2::4], rgba[3::4])]
    lines = [
        '// Generated by tools/generate-skin.py; do not edit.',
        '// Original char.png copied byte-for-byte; see port/assets/steve.source.json.',
        '#pragma once', '#include <cstdint>', 'namespace steve {',
        'constexpr int kSkinWidth = 64;', 'constexpr int kSkinHeight = 32;',
        f'constexpr char kSkinSourceSha256[] = "{digest}";',
        f'constexpr char kSkinRgbaSha256[] = "{rgba_digest}";',
        '// AARRGGBB integer, BGRA bytes on little-endian platforms; straight alpha.',
        'constexpr uint32_t kSkinPixels[kSkinWidth * kSkinHeight] = {'
    ]
    for offset in range(0, len(pixels), 8):
        lines.append('    ' + ', '.join(f'0x{pixel:08x}u' for pixel in pixels[offset:offset+8]) + ',')
    lines += ['};', '} // namespace steve', '']
    text = '\n'.join(lines)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text(encoding='utf-8') != text:
        args.output.write_text(text, encoding='utf-8')
    print(f'Generated {args.output}: 64x32 ARGB32, source SHA-256 {digest}')


if __name__ == '__main__':
    main()
