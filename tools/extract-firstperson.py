def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        outputs = generate(args.root)
        directory = args.root / 'jsapi/build/generated'
        for name, text in outputs.items():
            path = directory / name
            if args.check:
                if not path.exists() or path.read_bytes() != text.encode():
                    raise ValueError(str(path) + ' is missing/stale')
            elif not path.exists() or path.read_bytes() != text.encode():
                directory.mkdir(parents=True, exist_ok=True)
                path.write_bytes(text.encode())
        print(('Verified' if args.check else 'Generated') + ' OriginalFirstPerson: six Git-blob-verified 09df sources, raw-byte hashes, original transforms and 64x32 PNG')
    except (OSError, ValueError, KeyError, AttributeError) as error:
        print('extract-firstperson: ' + str(error), file=sys.stderr)
        return 1
    return 0


